ALTER TABLE role ADD COLUMN employee_level_id BIGINT;
ALTER TABLE role ADD CONSTRAINT fk_role_employee_level FOREIGN KEY (employee_level_id) REFERENCES employee_level(id);
CREATE INDEX idx_role_employee_level ON role(employee_level_id);

CREATE TABLE review_period_employee_level_configuration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_period_id BIGINT NOT NULL,
    employee_level_id BIGINT NOT NULL,
    CONSTRAINT fk_period_level_period FOREIGN KEY (review_period_id) REFERENCES annual_kpi_review_period(id),
    CONSTRAINT fk_period_level_employee_level FOREIGN KEY (employee_level_id) REFERENCES employee_level(id),
    company_kpi_weight NUMERIC(5,2),
    department_kpi_weight NUMERIC(5,2),
    individual_kpi_weight NUMERIC(5,2),
    CONSTRAINT uq_period_employee_level UNIQUE (review_period_id,employee_level_id),
    CONSTRAINT uq_period_level_config_id UNIQUE (review_period_id,id),
    CONSTRAINT chk_period_level_weight_ranges CHECK (
        company_kpi_weight BETWEEN 0 AND 100 AND department_kpi_weight BETWEEN 0 AND 100
        AND individual_kpi_weight BETWEEN 0 AND 100)
);
CREATE INDEX idx_period_level_employee_level ON review_period_employee_level_configuration(employee_level_id);
-- Preserve original configurations, including incomplete Drafts; do not apply example defaults retrospectively.
INSERT INTO review_period_employee_level_configuration(review_period_id,employee_level_id,company_kpi_weight,department_kpi_weight,individual_kpi_weight)
SELECT p.id,l.id,p.company_kpi_weight,p.department_kpi_weight,p.individual_kpi_weight
FROM annual_kpi_review_period p CROSS JOIN employee_level l;

