-- Do not infer historical Employee Levels from job names or current role assignments.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM review_period_participant)
       OR EXISTS (SELECT 1 FROM review_period_role_configuration c
                  JOIN annual_kpi_review_period p ON p.id=c.review_period_id WHERE p.status<>'DRAFT') THEN
        RAISE EXCEPTION 'V29 requires an explicit reviewed historical Employee Level mapping before migrating published role configurations or participants';
    END IF;
END $$;

CREATE TABLE employee_level (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL UNIQUE,
    display_order INTEGER NOT NULL UNIQUE,
    default_company_kpi_weight NUMERIC(5,2) NOT NULL,
    default_department_kpi_weight NUMERIC(5,2) NOT NULL,
    default_individual_kpi_weight NUMERIC(5,2) NOT NULL,
    CONSTRAINT chk_employee_level_defaults CHECK (
        default_company_kpi_weight BETWEEN 0 AND 100 AND default_department_kpi_weight BETWEEN 0 AND 100
        AND default_individual_kpi_weight BETWEEN 0 AND 100
        AND default_company_kpi_weight + default_department_kpi_weight + default_individual_kpi_weight = 100)
);
