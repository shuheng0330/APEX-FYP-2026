-- Guard immutable definitions even if an accidental ORM mutation reaches PostgreSQL.
CREATE FUNCTION guard_confirmed_kpi_definition() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE vid BIGINT;
BEGIN
    IF TG_TABLE_NAME='kpi' THEN vid=CASE WHEN TG_OP='INSERT' THEN NEW.version_id ELSE OLD.version_id END;
    ELSE SELECT version_id INTO vid FROM kpi WHERE id=CASE WHEN TG_OP='INSERT' THEN NEW.kpi_id ELSE OLD.kpi_id END;
    END IF;
    IF EXISTS(SELECT 1 FROM kpi_plan_version WHERE id=vid AND status IN ('EFFECTIVE','SUPERSEDED','CANCELLED')) THEN
        RAISE EXCEPTION 'Confirmed or cancelled KPI definitions are immutable' USING ERRCODE='23514';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
CREATE TRIGGER guard_kpi_definition BEFORE INSERT OR UPDATE OR DELETE ON kpi FOR EACH ROW EXECUTE FUNCTION guard_confirmed_kpi_definition();
CREATE TRIGGER guard_kpi_scoring BEFORE INSERT OR UPDATE OR DELETE ON kpi_scoring_definition FOR EACH ROW EXECUTE FUNCTION guard_confirmed_kpi_definition();
