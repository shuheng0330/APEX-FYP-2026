CREATE TABLE kpi_plan_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL, review_period_id BIGINT NOT NULL, level VARCHAR(20) NOT NULL,
    version_number INTEGER NOT NULL CHECK(version_number>0), base_version_id BIGINT,
    status VARCHAR(32) NOT NULL, revision_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL REFERENCES staff(id), updated_by UUID NOT NULL REFERENCES staff(id),
    requested_by UUID REFERENCES staff(id), prepared_by UUID REFERENCES staff(id), prepared_at TIMESTAMPTZ,
    submitted_at TIMESTAMPTZ, approved_by UUID REFERENCES staff(id), approved_at TIMESTAMPTZ,
    confirmed_by UUID REFERENCES staff(id), confirmed_at TIMESTAMPTZ, effective_at TIMESTAMPTZ,
    cancelled_by UUID REFERENCES staff(id), cancelled_at TIMESTAMPTZ, cancellation_reason TEXT,
    cancelled_from_state VARCHAR(32), latest_return_reason TEXT,
    latest_returned_by UUID REFERENCES staff(id), latest_returned_at TIMESTAMPTZ, latest_return_items JSONB,
    decision_history JSONB NOT NULL DEFAULT '[]'::jsonb,
    revision_required BOOLEAN NOT NULL DEFAULT false, lock_version BIGINT NOT NULL DEFAULT 0,
    UNIQUE(plan_id,version_number), UNIQUE(id,plan_id,review_period_id), UNIQUE(id,review_period_id,level),
    FOREIGN KEY(plan_id,review_period_id,level) REFERENCES kpi_plan(id,review_period_id,level),
    FOREIGN KEY(base_version_id,plan_id,review_period_id) REFERENCES kpi_plan_version(id,plan_id,review_period_id),
    CHECK(status IN ('REQUESTED','DRAFT','PENDING_APPROVAL','RETURNED','PENDING_MD_APPROVAL',
        'PENDING_HOD_CONFIRMATION','EFFECTIVE','SUPERSEDED','CANCELLED')),
    CHECK((version_number=1 AND base_version_id IS NULL AND revision_reason IS NULL) OR
        (version_number>1 AND base_version_id IS NOT NULL AND level IN ('COMPANY','DEPARTMENT')
            AND revision_reason IS NOT NULL AND length(trim(revision_reason)) BETWEEN 1 AND 10000)),
    CHECK(version_number=1 OR level<>'COMPANY' OR status IN ('DRAFT','EFFECTIVE','SUPERSEDED','CANCELLED')),
    CHECK(version_number=1 OR level<>'DEPARTMENT' OR (requested_by IS NOT NULL
        AND (prepared_by IS NULL OR requested_by<>prepared_by)
        AND (approved_by IS NULL OR (prepared_by IS NOT NULL AND approved_by<>prepared_by AND approved_by<>requested_by)))),
    CHECK(status NOT IN ('EFFECTIVE','SUPERSEDED') OR effective_at IS NOT NULL),
    CHECK(version_number=1 OR level<>'DEPARTMENT' OR status NOT IN ('PENDING_HOD_CONFIRMATION','EFFECTIVE','SUPERSEDED')
        OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)),
    CHECK(version_number=1 OR level<>'DEPARTMENT' OR status NOT IN ('EFFECTIVE','SUPERSEDED')
        OR (confirmed_by=requested_by AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL)),
    CHECK((status='CANCELLED' AND cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL
        AND cancellation_reason IS NOT NULL AND length(trim(cancellation_reason)) BETWEEN 1 AND 10000
        AND cancelled_from_state IN ('REQUESTED','DRAFT','RETURNED','PENDING_MD_APPROVAL','PENDING_HOD_CONFIRMATION'))
        OR (status<>'CANCELLED' AND cancelled_by IS NULL AND cancelled_at IS NULL AND cancellation_reason IS NULL AND cancelled_from_state IS NULL)),
    CHECK(latest_return_items IS NULL OR jsonb_typeof(latest_return_items)='array'),
    CHECK(jsonb_typeof(decision_history)='array')
);
