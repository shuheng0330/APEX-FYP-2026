CREATE FUNCTION guard_period_frequency_policy() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status <> 'DRAFT' AND NEW.frequency_policy IS DISTINCT FROM OLD.frequency_policy THEN
        RAISE EXCEPTION 'Published frequency policy cannot change' USING ERRCODE='23514';
    END IF;
    IF OLD.frequency_policy='DEPARTMENT_BASED' AND OLD.status <> 'DRAFT' AND
        (NEW.status='DRAFT' OR ROW(NEW.start_date,NEW.end_date,NEW.self_assessment_days_after_checkpoint,
            NEW.superior_assessment_days_after_self_deadline,NEW.participants_snapshotted_at)
        IS DISTINCT FROM ROW(OLD.start_date,OLD.end_date,OLD.self_assessment_days_after_checkpoint,
            OLD.superior_assessment_days_after_self_deadline,OLD.participants_snapshotted_at))
        AND OLD.participants_snapshotted_at IS NOT NULL THEN
        RAISE EXCEPTION 'Published Department schedules and enrolment are frozen' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_period_frequency_policy BEFORE UPDATE ON annual_kpi_review_period
    FOR EACH ROW EXECUTE FUNCTION guard_period_frequency_policy();

CREATE FUNCTION guard_period_department_configuration() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE period_row RECORD; period_id BIGINT;
BEGIN
    IF TG_OP='UPDATE' AND ROW(NEW.id,NEW.review_period_id,NEW.department_id)
        IS DISTINCT FROM ROW(OLD.id,OLD.review_period_id,OLD.department_id) THEN
        RAISE EXCEPTION 'Department configuration identity cannot change' USING ERRCODE='23514';
    END IF;
    period_id := CASE WHEN TG_OP='DELETE' THEN OLD.review_period_id ELSE NEW.review_period_id END;
    SELECT * INTO period_row FROM annual_kpi_review_period WHERE id=period_id FOR UPDATE;
    IF period_row.frequency_policy <> 'DEPARTMENT_BASED' OR period_row.participants_snapshotted_at IS NOT NULL
        OR (TG_OP <> 'INSERT' AND period_row.status <> 'DRAFT') THEN
        RAISE EXCEPTION 'Department configuration is editable only before publication' USING ERRCODE='23514';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_period_department_configuration BEFORE INSERT OR UPDATE OR DELETE
    ON review_period_department_configuration FOR EACH ROW EXECUTE FUNCTION guard_period_department_configuration();

CREATE FUNCTION guard_participant_department_frequency() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE policy VARCHAR(24);
BEGIN
    IF TG_OP='UPDATE' AND ROW(NEW.department_configuration_id,NEW.department_id,NEW.review_frequency,NEW.review_period_id)
        IS DISTINCT FROM ROW(OLD.department_configuration_id,OLD.department_id,OLD.review_frequency,OLD.review_period_id) THEN
        RAISE EXCEPTION 'Recorded participant frequency and Department cannot change' USING ERRCODE='23514';
    END IF;
    SELECT frequency_policy INTO policy FROM annual_kpi_review_period WHERE id=NEW.review_period_id;
    IF policy='DEPARTMENT_BASED' AND (NEW.department_configuration_id IS NULL OR NEW.department_id IS NULL) THEN
        RAISE EXCEPTION 'A recorded Department configuration is required' USING ERRCODE='23514';
    END IF;
    IF policy='ROLE_BASED' AND NEW.department_configuration_id IS NOT NULL THEN
        RAISE EXCEPTION 'Role-based participants cannot adopt a Department schedule' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_participant_department_frequency BEFORE INSERT OR UPDATE ON review_period_participant
    FOR EACH ROW EXECUTE FUNCTION guard_participant_department_frequency();

CREATE FUNCTION guard_department_checkpoint_schedule() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE period_id BIGINT;
BEGIN
    period_id := CASE WHEN TG_OP='DELETE' THEN OLD.review_period_id ELSE NEW.review_period_id END;
    IF TG_OP='UPDATE' AND NEW.review_period_id IS DISTINCT FROM OLD.review_period_id THEN
        RAISE EXCEPTION 'Checkpoint period cannot change' USING ERRCODE='23514';
    END IF;
    IF EXISTS (SELECT 1 FROM annual_kpi_review_period WHERE id=period_id
        AND frequency_policy='DEPARTMENT_BASED' AND participants_snapshotted_at IS NOT NULL) THEN
        RAISE EXCEPTION 'Published Department checkpoints cannot change' USING ERRCODE='23514';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_department_checkpoint_schedule BEFORE INSERT OR UPDATE OR DELETE ON review_checkpoint
    FOR EACH ROW EXECUTE FUNCTION guard_department_checkpoint_schedule();

CREATE FUNCTION guard_company_checkpoint_source() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE policy VARCHAR(24); employee_end DATE;
BEGIN
    SELECT frequency_policy INTO policy FROM annual_kpi_review_period WHERE id=NEW.review_period_id;
    -- Retain compatibility for old clients writing Role-based aggregates.
    IF policy='ROLE_BASED' AND NEW.company_checkpoint_id IS NULL THEN NEW.company_checkpoint_id:=NEW.checkpoint_id; END IF;
    IF TG_OP='UPDATE' AND NEW.company_checkpoint_id IS DISTINCT FROM OLD.company_checkpoint_id THEN
        RAISE EXCEPTION 'Recorded Company reporting checkpoint cannot change' USING ERRCODE='23514';
    END IF;
    IF policy='ROLE_BASED' AND NEW.company_checkpoint_id IS DISTINCT FROM NEW.checkpoint_id THEN
        RAISE EXCEPTION 'Role-based Company results must use the employee checkpoint' USING ERRCODE='23514';
    END IF;
    IF policy='DEPARTMENT_BASED' THEN
        SELECT end_date INTO employee_end FROM review_checkpoint WHERE id=NEW.checkpoint_id AND review_period_id=NEW.review_period_id;
        IF NOT EXISTS (SELECT 1 FROM review_checkpoint WHERE id=NEW.company_checkpoint_id
            AND review_period_id=NEW.review_period_id AND review_frequency='MONTHLY' AND end_date=employee_end) THEN
            RAISE EXCEPTION 'Company results require the matching Monthly end date in this period' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_company_checkpoint_source BEFORE INSERT OR UPDATE ON kpi_checkpoint_result
    FOR EACH ROW EXECUTE FUNCTION guard_company_checkpoint_source();
