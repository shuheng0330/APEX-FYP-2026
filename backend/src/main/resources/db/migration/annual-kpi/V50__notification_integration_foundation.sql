-- The shared notification entity may already have been deployed by the training module.
-- Adopt compatible existing records without changing their contents or email status.
CREATE TABLE IF NOT EXISTS user_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id UUID NOT NULL,
    type VARCHAR(60) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    link VARCHAR(300),
    dedupe_key VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    email_status VARCHAR(20) NOT NULL,
    email_attempts INTEGER NOT NULL,
    email_error TEXT,
    emailed_at TIMESTAMP WITH TIME ZONE
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM (VALUES
            ('id', 'int8', NULL::INTEGER, true),
            ('recipient_id', 'uuid', NULL, true),
            ('type', 'varchar', 60, true),
            ('title', 'varchar', 200, true),
            ('body', 'text', NULL, true),
            ('link', 'varchar', 300, false),
            ('dedupe_key', 'varchar', 200, false),
            ('created_at', 'timestamptz', NULL, true),
            ('read_at', 'timestamptz', NULL, false),
            ('email_status', 'varchar', 20, true),
            ('email_attempts', 'int4', NULL, true),
            ('email_error', 'text', NULL, false),
            ('emailed_at', 'timestamptz', NULL, false)
        ) AS expected(name, type_name, min_length, required)
        LEFT JOIN information_schema.columns c
            ON c.table_schema = current_schema() AND c.table_name = 'user_notification'
            AND c.column_name = expected.name
        WHERE c.column_name IS NULL OR c.udt_name <> expected.type_name
            OR (expected.min_length IS NOT NULL AND c.character_maximum_length < expected.min_length)
            OR (expected.required AND c.is_nullable <> 'NO')
    ) THEN
        RAISE EXCEPTION 'Existing user_notification schema is incompatible; review before migration';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'user_notification' AND column_name = 'id'
          AND (is_identity = 'YES' OR column_default LIKE 'nextval(%')
    ) THEN
        RAISE EXCEPTION 'user_notification.id requires an existing identity or sequence default';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_index i
        JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = i.indkey[0]
        WHERE i.indrelid = 'user_notification'::regclass
          AND i.indisunique AND i.indisvalid AND i.indimmediate
          AND i.indpred IS NULL AND i.indexprs IS NULL
          AND i.indnkeyatts = 1 AND a.attname = 'dedupe_key'
    ) THEN
        -- Existing duplicate keys deliberately fail migration; never delete or merge audit records.
        CREATE UNIQUE INDEX uq_user_notification_dedupe_key ON user_notification (dedupe_key);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_user_notification_recipient ON user_notification (recipient_id, created_at);
