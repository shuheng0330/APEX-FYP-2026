-- Controlled Open-period corrections only. No assignment, score or permission backfill.
CREATE TABLE attitude_configuration_assignment_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    review_period_id BIGINT NOT NULL REFERENCES annual_kpi_review_period(id),
    previous_configuration_id BIGINT NOT NULL REFERENCES attitude_configuration(id),
    configuration_id BIGINT NOT NULL REFERENCES attitude_configuration(id),
    actor_id UUID NOT NULL REFERENCES staff(id),
    recorded_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    CONSTRAINT ck_attitude_assignment_changed CHECK (previous_configuration_id <> configuration_id),
    CONSTRAINT ck_attitude_assignment_reason CHECK (length(trim(reason)) > 0)
);
CREATE INDEX idx_attitude_assignment_period ON attitude_configuration_assignment_activity(review_period_id,id);

CREATE FUNCTION reject_attitude_assignment_activity_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Attitude configuration assignment activity is append-only';
END;
$$;
CREATE TRIGGER trg_attitude_assignment_activity_immutable
    BEFORE UPDATE OR DELETE ON attitude_configuration_assignment_activity
    FOR EACH ROW EXECUTE FUNCTION reject_attitude_assignment_activity_change();
