CREATE TABLE attitude_configuration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED')),
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL REFERENCES staff(id), updated_by UUID NOT NULL REFERENCES staff(id),
    published_at TIMESTAMPTZ, published_by UUID REFERENCES staff(id),
    CONSTRAINT ck_attitude_publication CHECK (
        (status='DRAFT' AND published_at IS NULL AND published_by IS NULL) OR
        (status='PUBLISHED' AND published_at IS NOT NULL AND published_by IS NOT NULL AND name IS NOT NULL AND length(trim(name))>0))
);
CREATE INDEX idx_attitude_configuration_publication ON attitude_configuration(status,published_at DESC,id DESC);

CREATE TABLE attitude_criterion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configuration_id BIGINT NOT NULL REFERENCES attitude_configuration(id),
    name VARCHAR(255), description TEXT,
    criterion_type VARCHAR(30) NOT NULL CHECK (criterion_type IN ('SHARED_CORE_VALUE','FORMAT_SPECIFIC')),
    evaluation_format VARCHAR(20) CHECK (evaluation_format IN ('MANAGER','SALES','OTHERS')),
    active BOOLEAN NOT NULL DEFAULT true,
    display_order INTEGER NOT NULL CHECK (display_order>=0),
    CONSTRAINT ck_attitude_criterion_scope CHECK (
        (criterion_type='SHARED_CORE_VALUE' AND evaluation_format IS NULL) OR
        (criterion_type='FORMAT_SPECIFIC' AND evaluation_format IS NOT NULL)),
    CONSTRAINT ck_attitude_criterion_description CHECK (description IS NULL OR length(description)<=10000)
);
CREATE INDEX idx_attitude_criterion_configuration ON attitude_criterion(configuration_id,display_order,id);

CREATE TABLE attitude_rating_definition (
    configuration_id BIGINT NOT NULL REFERENCES attitude_configuration(id),
    point INTEGER NOT NULL CHECK (point BETWEEN 1 AND 5),
    label VARCHAR(255), description TEXT CHECK (description IS NULL OR length(description)<=10000),
    PRIMARY KEY(configuration_id,point)
);
CREATE TABLE attitude_role_format_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configuration_id BIGINT NOT NULL REFERENCES attitude_configuration(id),
    role_id BIGINT NOT NULL REFERENCES role(id),
    evaluation_format VARCHAR(20) NOT NULL CHECK (evaluation_format IN ('MANAGER','SALES','OTHERS')),
    CONSTRAINT uq_attitude_configuration_role UNIQUE(configuration_id,role_id)
);
CREATE INDEX idx_attitude_role_mapping_role ON attitude_role_format_mapping(role_id);

