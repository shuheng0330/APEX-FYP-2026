DECLARE table_name TEXT; populated BOOLEAN;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['kpi_central_result','kpi_central_result_item','kpi_central_result_evidence',
        'company_kpi_result_delegate','kpi_checkpoint_result']
    LOOP
        IF to_regclass(table_name) IS NOT NULL THEN
            EXECUTE format('SELECT EXISTS(SELECT 1 FROM %I)',table_name) INTO populated;
            IF populated THEN
                RAISE EXCEPTION 'Untracked central KPI tables must be empty before migration: %',table_name USING ERRCODE='23514';
            END IF;
        END IF;
    END LOOP;
END $$;
