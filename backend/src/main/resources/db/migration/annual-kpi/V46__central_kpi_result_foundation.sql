CREATE FUNCTION guard_central_result() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE predecessor kpi_central_result%ROWTYPE;
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.status<>'DRAFT' THEN
            RAISE EXCEPTION 'A central result must start as a Draft' USING ERRCODE='23514';
        END IF;
    ELSE
        IF OLD.status<>'DRAFT' THEN
            -- The ORM optimistic-lock counter is operational metadata, not published content.
            IF TG_OP='UPDATE' THEN
                IF OLD.status='PUBLISHED' AND NEW.status='SUPERSEDED'
                    AND (to_jsonb(NEW)-ARRAY['status','lock_version'])=(to_jsonb(OLD)-ARRAY['status','lock_version']) THEN
                    RETURN NEW;
                END IF;
            END IF;
            RAISE EXCEPTION 'Published central results are immutable; create a correction edition' USING ERRCODE='23514';
        END IF;
        IF TG_OP='DELETE' THEN RETURN OLD; END IF;
        IF ROW(NEW.id,NEW.review_period_id,NEW.checkpoint_id,NEW.review_frequency,NEW.plan_version_id,NEW.level,
                NEW.edition_number,NEW.previous_edition_id,NEW.created_by,NEW.created_at)
            IS DISTINCT FROM ROW(OLD.id,OLD.review_period_id,OLD.checkpoint_id,OLD.review_frequency,OLD.plan_version_id,
                OLD.level,OLD.edition_number,OLD.previous_edition_id,OLD.created_by,OLD.created_at)
            OR NEW.status='SUPERSEDED' THEN
            RAISE EXCEPTION 'Central result scope and edition origin cannot change' USING ERRCODE='23514';
        END IF;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM annual_kpi_review_period
        WHERE id=NEW.review_period_id AND assessment_model='CENTRAL_RESULTS') THEN
        RAISE EXCEPTION 'Central results require the central assessment model' USING ERRCODE='23514';
    END IF;
    IF EXISTS (SELECT 1 FROM kpi_plan_version WHERE id=NEW.plan_version_id
        AND status NOT IN ('EFFECTIVE','SUPERSEDED')) THEN
        RAISE EXCEPTION 'Central results require a confirmed KPI version' USING ERRCODE='23514';
    END IF;
    IF NEW.previous_edition_id IS NOT NULL THEN
        SELECT * INTO predecessor FROM kpi_central_result WHERE id=NEW.previous_edition_id FOR KEY SHARE;
        IF FOUND AND (predecessor.status='DRAFT' OR predecessor.edition_number>=NEW.edition_number) THEN
            RAISE EXCEPTION 'A correction must follow an earlier published edition' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_central_result BEFORE INSERT OR UPDATE OR DELETE ON kpi_central_result
    FOR EACH ROW EXECUTE FUNCTION guard_central_result();

CREATE FUNCTION guard_central_result_child() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE old_result BIGINT; new_result BIGINT; result_row RECORD;
BEGIN
    IF TG_TABLE_NAME='kpi_central_result_item' THEN
        IF TG_OP<>'INSERT' THEN old_result=OLD.result_id; END IF;
        IF TG_OP<>'DELETE' THEN new_result=NEW.result_id; END IF;
    ELSE
        -- Lock the item first, preventing a concurrent reparent from bypassing its result lock.
        IF TG_OP<>'INSERT' THEN
            SELECT result_id INTO old_result FROM kpi_central_result_item WHERE id=OLD.item_id FOR UPDATE;
        END IF;
        IF TG_OP<>'DELETE' THEN
            SELECT result_id INTO new_result FROM kpi_central_result_item WHERE id=NEW.item_id FOR UPDATE;
        END IF;
    END IF;
    -- Lock both old/new parents in a stable order, including moves from a Draft to a publication.
    FOR result_row IN SELECT id,status FROM kpi_central_result
        WHERE id IN (old_result,new_result) ORDER BY id FOR UPDATE
    LOOP
        IF result_row.status<>'DRAFT' THEN
            RAISE EXCEPTION 'Published central result items and evidence are immutable' USING ERRCODE='23514';
        END IF;
    END LOOP;
    IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
CREATE TRIGGER guard_central_item BEFORE INSERT OR UPDATE OR DELETE ON kpi_central_result_item
    FOR EACH ROW EXECUTE FUNCTION guard_central_result_child();
CREATE TRIGGER guard_central_evidence BEFORE INSERT OR UPDATE OR DELETE ON kpi_central_result_evidence
    FOR EACH ROW EXECUTE FUNCTION guard_central_result_child();

