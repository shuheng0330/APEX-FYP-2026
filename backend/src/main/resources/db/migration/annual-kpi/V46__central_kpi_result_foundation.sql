CREATE FUNCTION guard_checkpoint_result_bindings() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE participant_department BIGINT; version_row RECORD;
BEGIN
    IF TG_OP='UPDATE' THEN
        IF ROW(NEW.id,NEW.participant_id,NEW.review_period_id,NEW.checkpoint_id,NEW.review_frequency)
            IS DISTINCT FROM ROW(OLD.id,OLD.participant_id,OLD.review_period_id,OLD.checkpoint_id,OLD.review_frequency)
            OR (OLD.company_version_id IS NOT NULL AND NEW.company_version_id IS DISTINCT FROM OLD.company_version_id)
            OR (OLD.department_version_id IS NOT NULL AND NEW.department_version_id IS DISTINCT FROM OLD.department_version_id)
            OR (OLD.individual_version_id IS NOT NULL AND NEW.individual_version_id IS DISTINCT FROM OLD.individual_version_id) THEN
            RAISE EXCEPTION 'Started checkpoint version bindings cannot change' USING ERRCODE='23514';
        END IF;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM annual_kpi_review_period
        WHERE id=NEW.review_period_id AND assessment_model='CENTRAL_RESULTS') THEN
        RAISE EXCEPTION 'Checkpoint aggregates require the central assessment model' USING ERRCODE='23514';
    END IF;
    SELECT department_id INTO participant_department FROM review_period_participant WHERE id=NEW.participant_id;
    FOR version_row IN SELECT v.id,v.status,p.department_id,p.owner_participant_id
        FROM kpi_plan_version v JOIN kpi_plan p ON p.id=v.plan_id
        WHERE v.id IN (NEW.company_version_id,NEW.department_version_id,NEW.individual_version_id)
    LOOP
        IF version_row.status NOT IN ('EFFECTIVE','SUPERSEDED') THEN
            RAISE EXCEPTION 'Checkpoint bindings require confirmed KPI versions' USING ERRCODE='23514';
        END IF;
        IF version_row.id=NEW.department_version_id AND version_row.department_id IS DISTINCT FROM participant_department THEN
            RAISE EXCEPTION 'Department version does not match the participant recorded Department' USING ERRCODE='23514';
        END IF;
        IF version_row.id=NEW.individual_version_id AND version_row.owner_participant_id IS DISTINCT FROM NEW.participant_id THEN
            RAISE EXCEPTION 'Individual version does not belong to the participant' USING ERRCODE='23514';
        END IF;
    END LOOP;
    IF EXISTS (SELECT 1 FROM kpi_central_result
        WHERE id IN (NEW.company_result_id,NEW.department_result_id) AND status='DRAFT') THEN
        RAISE EXCEPTION 'Draft central results cannot contribute to checkpoint scores' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_checkpoint_result_bindings BEFORE INSERT OR UPDATE ON kpi_checkpoint_result
    FOR EACH ROW EXECUTE FUNCTION guard_checkpoint_result_bindings();

