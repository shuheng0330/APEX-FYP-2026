-- Annual KPI/Attitude appraisals are independent of legacy competency-cycle appraisals.
ALTER TABLE review_period_participant ADD CONSTRAINT uq_annual_appraisal_owner
    UNIQUE(id,review_period_id,staff_id);

CREATE TABLE annual_appraisal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT NOT NULL, review_period_id BIGINT NOT NULL, employee_id UUID NOT NULL,
    superior_id UUID NOT NULL REFERENCES staff(id),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    recommendation VARCHAR(24), justification TEXT, final_decision VARCHAR(24), override_reason TEXT,
    latest_return_reason TEXT, returned_recommendation VARCHAR(24), returned_justification TEXT,
    snapshot JSONB,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL REFERENCES staff(id), updated_by UUID NOT NULL REFERENCES staff(id),
    submitted_at TIMESTAMPTZ, submitted_late BOOLEAN,
    reviewed_at TIMESTAMPTZ, reviewed_by UUID REFERENCES staff(id), reviewed_late BOOLEAN,
    lock_version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_annual_appraisal_participant UNIQUE(participant_id),
    CONSTRAINT uq_annual_appraisal_employee_period UNIQUE(employee_id,review_period_id),
    CONSTRAINT fk_annual_appraisal_owner FOREIGN KEY(participant_id,review_period_id,employee_id)
        REFERENCES review_period_participant(id,review_period_id,staff_id),
    CONSTRAINT ck_annual_appraisal_status CHECK(status IN ('DRAFT','PENDING_REVIEW','RETURNED','APPROVED')),
    CONSTRAINT ck_annual_appraisal_choices CHECK(
        (recommendation IS NULL OR recommendation IN ('PROMOTION','SALARY_INCREMENT','BOTH','NO_RECOMMENDATION')) AND
        (final_decision IS NULL OR final_decision IN ('PROMOTION','SALARY_INCREMENT','BOTH','NO_RECOMMENDATION')) AND
        (returned_recommendation IS NULL OR returned_recommendation IN ('PROMOTION','SALARY_INCREMENT','BOTH','NO_RECOMMENDATION'))),
    CONSTRAINT ck_annual_appraisal_text CHECK(
        (justification IS NULL OR length(justification)<=10000) AND
        (override_reason IS NULL OR length(override_reason)<=10000) AND
        (latest_return_reason IS NULL OR length(latest_return_reason)<=10000) AND
        (returned_justification IS NULL OR length(returned_justification)<=10000)),
    CONSTRAINT ck_annual_appraisal_submission CHECK(status IN ('DRAFT','RETURNED') OR
        (recommendation IS NOT NULL AND justification IS NOT NULL AND length(btrim(justification))>0 AND
         submitted_at IS NOT NULL AND submitted_late IS NOT NULL AND snapshot IS NOT NULL AND
         jsonb_typeof(snapshot)='object' AND snapshot ? 'finalScore' AND jsonb_typeof(snapshot->'finalScore')='number' AND
         (snapshot->>'finalScore')::numeric BETWEEN 0 AND 100)),
    CONSTRAINT ck_annual_appraisal_return CHECK(status<>'RETURNED' OR
        (latest_return_reason IS NOT NULL AND length(btrim(latest_return_reason))>0 AND
         returned_recommendation IS NOT NULL AND returned_justification IS NOT NULL)),
    CONSTRAINT ck_annual_appraisal_decision CHECK(
        (status<>'APPROVED' AND final_decision IS NULL AND override_reason IS NULL) OR
        (status='APPROVED' AND final_decision IS NOT NULL AND reviewed_at IS NOT NULL AND
         reviewed_by IS NOT NULL AND reviewed_by<>superior_id AND reviewed_by<>employee_id AND reviewed_late IS NOT NULL AND
         (final_decision=recommendation AND override_reason IS NULL OR
          final_decision<>recommendation AND override_reason IS NOT NULL AND length(btrim(override_reason))>0)))
);
CREATE INDEX idx_annual_appraisal_queue ON annual_appraisal(review_period_id,status,submitted_at);
CREATE INDEX idx_annual_appraisal_superior ON annual_appraisal(superior_id,review_period_id);

CREATE TABLE annual_appraisal_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appraisal_id BIGINT NOT NULL REFERENCES annual_appraisal(id),
    action VARCHAR(24) NOT NULL CHECK(action IN ('DRAFT_CREATED','DRAFT_SAVED','SUBMITTED','RESUBMITTED','APPROVED','OVERRIDDEN','RETURNED')),
    actor_id UUID NOT NULL REFERENCES staff(id), occurred_at TIMESTAMPTZ NOT NULL,
    reason TEXT, recommendation VARCHAR(24), justification TEXT, final_decision VARCHAR(24), snapshot JSONB,
    CONSTRAINT ck_annual_activity_reason CHECK(action NOT IN ('OVERRIDDEN','RETURNED') OR
        reason IS NOT NULL AND length(btrim(reason)) BETWEEN 1 AND 10000)
);
CREATE INDEX idx_annual_appraisal_activity ON annual_appraisal_activity(appraisal_id,id);

CREATE FUNCTION guard_annual_appraisal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.status<>'DRAFT' THEN
            RAISE EXCEPTION 'An annual appraisal must start as a Draft' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'Annual appraisal history cannot be deleted' USING ERRCODE='23514';
    END IF;
    IF OLD.status='APPROVED' THEN
        RAISE EXCEPTION 'Approved annual appraisals are immutable' USING ERRCODE='23514';
    END IF;
    IF (NEW.participant_id,NEW.review_period_id,NEW.employee_id,NEW.superior_id,NEW.created_at,NEW.created_by)
        IS DISTINCT FROM (OLD.participant_id,OLD.review_period_id,OLD.employee_id,OLD.superior_id,OLD.created_at,OLD.created_by) THEN
        RAISE EXCEPTION 'Annual appraisal ownership cannot change' USING ERRCODE='23514';
    END IF;
    IF NEW.status<>OLD.status AND NOT (
        OLD.status IN ('DRAFT','RETURNED') AND NEW.status='PENDING_REVIEW' OR
        OLD.status='PENDING_REVIEW' AND NEW.status IN ('RETURNED','APPROVED')) THEN
        RAISE EXCEPTION 'Invalid annual appraisal transition' USING ERRCODE='23514';
    END IF;
    IF OLD.status='PENDING_REVIEW' AND (NEW.recommendation,NEW.justification,NEW.snapshot,NEW.submitted_at,NEW.submitted_late)
        IS DISTINCT FROM (OLD.recommendation,OLD.justification,OLD.snapshot,OLD.submitted_at,OLD.submitted_late) THEN
        RAISE EXCEPTION 'Submitted appraisal contents are read-only' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_annual_appraisal BEFORE INSERT OR UPDATE OR DELETE ON annual_appraisal
    FOR EACH ROW EXECUTE FUNCTION guard_annual_appraisal();

CREATE FUNCTION guard_annual_appraisal_activity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Annual appraisal activity is append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER guard_annual_appraisal_activity BEFORE UPDATE OR DELETE ON annual_appraisal_activity
    FOR EACH ROW EXECUTE FUNCTION guard_annual_appraisal_activity();

