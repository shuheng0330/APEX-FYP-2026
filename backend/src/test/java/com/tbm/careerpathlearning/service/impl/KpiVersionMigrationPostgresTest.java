                        +"SELECT plan_id,review_period_id,level,2,id,'REQUESTED','Change target',now(),now(),created_by,updated_by,"
                        +"'00000000-0000-0000-0000-000000000002','HR_MD','00000000-0000-0000-0000-000000000001' FROM kpi_plan_version WHERE plan_id=3 AND version_number=1";
