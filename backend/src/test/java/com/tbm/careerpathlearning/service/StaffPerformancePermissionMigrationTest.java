package com.tbm.careerpathlearning.service;

import com.tbm.careerpathlearning.enums.AuthorityName;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;

class StaffPerformancePermissionMigrationTest {
    @Test void forwardMigrationRegistersOnlyViewingPermissionsAndPreservesExistingGrants() {
        var source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:performance_permissions_" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE authority(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) UNIQUE, description_key VARCHAR(255), label_key VARCHAR(255), CONSTRAINT authority_name_check CHECK(name='ROLE_USER'))");
        jdbc.execute("CREATE TABLE role_authority(role_id BIGINT, authority_id BIGINT REFERENCES authority(id))");
        jdbc.update("INSERT INTO authority(name, description_key, label_key) VALUES('ROLE_USER','original description','original label')");
        jdbc.update("INSERT INTO role_authority VALUES(7,1)");
        var beforeAuthorities = jdbc.queryForList("SELECT * FROM authority");
        var beforeGrants = jdbc.queryForList("SELECT * FROM role_authority");
        new ResourceDatabasePopulator(new ClassPathResource("db/migration/annual-kpi/V51__annual_performance_view_permissions.sql")).execute(source);
        assertEquals(beforeAuthorities, jdbc.queryForList("SELECT * FROM authority WHERE name='ROLE_USER'"));
        assertEquals(beforeGrants, jdbc.queryForList("SELECT * FROM role_authority"));
        assertEquals(4, jdbc.queryForObject("SELECT count(*) FROM authority", Integer.class));
        var registered = jdbc.queryForList("SELECT name FROM authority WHERE name<>'ROLE_USER' ORDER BY name", String.class);
        assertEquals(List.of(StaffPerformanceAccess.DEPARTMENT, StaffPerformanceAccess.ORGANISATION, StaffPerformanceAccess.TEAM), registered);
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class,
                () -> jdbc.update("INSERT INTO authority(name) VALUES('UNRECOGNISED')"));
        // Existing permissions must still be accepted by the expanded enum constraint.
        for (var authority : AuthorityName.values())
            if (!jdbc.queryForList("SELECT name FROM authority", String.class).contains(authority.name()))
                jdbc.update("INSERT INTO authority(name) VALUES(?)", authority.name());
        assertEquals(AuthorityName.values().length, jdbc.queryForObject("SELECT count(*) FROM authority", Integer.class));
        jdbc.execute("SHUTDOWN");
    }
}
